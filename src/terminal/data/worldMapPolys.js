// worldMapPolys.js — Shared simplified world map polygons
// Projection: d3.geoNaturalEarth1  ViewBox: 0 0 800 400
// Scale 127 · translate [400, 205]
//   Poles at y≈24 (N) / y≈386 (S) · antimeridian at x≈53 / x≈747

import { geoNaturalEarth1, geoPath, geoGraticule } from 'd3-geo';

// ── Projection setup ─────────────────────────────────────────────────────────
export const projection = geoNaturalEarth1()
  .scale(127)
  .translate([400, 205]);

const pathGen = geoPath(projection);

// ── Helpers ───────────────────────────────────────────────────────────────────
// Convert [lon, lat][] to a closed GeoJSON Polygon → SVG path string.
const poly = pts => {
  const ring = [...pts, pts[0]];
  return pathGen({ type: 'Polygon', coordinates: [ring] }) || '';
};

// Project lon/lat → SVG pixel coords
export const toMapXY = (lon, lat) => {
  const r = projection([lon, lat]);
  return r ? [r[0], r[1]] : [400, 205];
};

// ── Graticule ─────────────────────────────────────────────────────────────────
// 30° step grid — natural earth curves look great at this resolution
const gratGen = geoGraticule().step([30, 30]);
export const GRATICULE_PATH = pathGen(gratGen()) || '';

// Equator as a separate, distinctly-styled path
export const EQUATOR_PATH = pathGen({
  type: 'LineString',
  coordinates: Array.from({ length: 37 }, (_, i) => [-180 + i * 10, 0]),
}) || '';

